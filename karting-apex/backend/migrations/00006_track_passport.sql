-- +goose Up
-- Паспорт трассы (F5): характеристики, которые нельзя вывести из геометрии.
-- Длина круга, число поворотов, направление вращения и главная прямая НЕ хранятся —
-- они считаются из geometry на бэкенде (internal/track), поэтому не могут разъехаться
-- с контуром, который рисуется на схеме. Значения в комментариях ниже посчитаны по
-- уже округлённым координатам, то есть по тому контуру, что реально лежит в строке.
ALTER TABLE routes
    ADD COLUMN surface       text,
    ADD COLUMN width_m       numeric(4,1),
    ADD COLUMN elevation_m   numeric(4,1),
    ADD COLUMN opened_year   integer,
    ADD COLUMN kart_model    text,
    ADD COLUMN kart_power_hp integer;

ALTER TABLE routes
    ADD CONSTRAINT routes_width_chk       CHECK (width_m IS NULL OR width_m > 0),
    ADD CONSTRAINT routes_elevation_chk   CHECK (elevation_m IS NULL OR elevation_m >= 0),
    ADD CONSTRAINT routes_opened_year_chk CHECK (opened_year IS NULL OR opened_year BETWEEN 1950 AND 2100),
    ADD CONSTRAINT routes_kart_power_chk  CHECK (kart_power_hp IS NULL OR kart_power_hp > 0);

